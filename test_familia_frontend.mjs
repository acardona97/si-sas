assert.equal(enviado.url,'/api/enviar-asistencia');
assert.ok(enviado.body.get('zip'));
console.log('OK extracción, generación multipart con payload y soportes, asistencia con el último ZIP');
dom.window.close();
console.log('OK test_familia_frontend');
