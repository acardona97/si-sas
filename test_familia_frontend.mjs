assert.equal(w.validateStep(2),false);
assert.match(alerts.at(-1), /parentesco/);
set('acc1_parentesco','Fundador');
assert.equal(w.validateStep(2),true,alerts.at(-1));
const pct = w.document.querySelector('[data-escenario="A+B"] input');
